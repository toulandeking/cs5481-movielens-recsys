"""
cs5481 MovieLens-1M recommender
==============================

app/streamlit_app.py  —  推荐系统演示界面
-----------------------------------------
满足任务书对「Movie Recommendation System Presentation (10%)」的要求：

  * "Present your movie recommendation system in the form of a web or mobile
     application, notebook, or equivalent interactive interface."
  * "The interface should accept **a user or sample profile** and display
     recommendations."
  * "Display movie titles and genres and **compare the recommendations
     generated by the different algorithms**."

因此界面分两个 Tab：
  Tab 1「选用户」   —— 输入一个 uid（= a user），三算法并排对比，显示片名 + 类型
  Tab 2「输画像」   —— 输入性别 / 年龄 / 偏好类型（= a sample profile）

设计要点
~~~~~~~~
1. **只读结果文件，不加载模型**。所以即使某台机器装不上 lightfm / torch，
   界面依然能展示该模型的推荐 —— 前提是 `top10.parquet` 存在。
2. **优雅降级**：缺哪个模型的产物就显示"待生成"，其余照常工作。
3. 产物搜索会同时看 `results/<model>/` 与 `outputs/<model>*/`，
   因为不同成员的导出位置不完全一致。

运行
~~~~
    python -m pip install streamlit
    streamlit run app/streamlit_app.py

必须从**仓库根目录**启动（或直接给绝对路径），因为要 import `src.*`。
"""

from __future__ import annotations

import random
import sys
from pathlib import Path

# Streamlit 只把脚本所在目录加进 sys.path，这里补上仓库根目录
ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import json

import pandas as pd
import streamlit as st

from src.contract import K, N_ITEMS, N_USERS, read_canon_table

# =============================================================================
# 常量与产物定位
# =============================================================================
MODELS = ("ItemCF", "LightFM", "LRURec")
MODEL_SLUG = {"ItemCF": "itemcf", "LightFM": "lightfm", "LRURec": "lrurec"}
RESULTS_DIR = ROOT / "results"
OUTPUTS_DIR = ROOT / "outputs"


def _first_existing(candidates: list[Path]) -> Path | None:
    for p in candidates:
        if p.is_file():
            return p
    return None


@st.cache_data(show_spinner=False)
def find_metrics(slug: str) -> Path | None:
    """指标 JSON 的可能位置。"""
    return _first_existing([
        OUTPUTS_DIR / "metrics" / f"{slug}_test.json",
        RESULTS_DIR / slug / f"{slug}_test.json",
        RESULTS_DIR / slug / "test.json",
    ])


@st.cache_data(show_spinner=False)
def find_top10(slug: str) -> Path | None:
    """top-10 推荐表的可能位置（各成员导出位置不一致）。"""
    return _first_existing([
        OUTPUTS_DIR / "top10" / f"{slug}.parquet",
        RESULTS_DIR / slug / "top10.parquet",
        RESULTS_DIR / slug / f"{slug}_top10.parquet",
        OUTPUTS_DIR / f"{slug}_top10.parquet",
    ])


# =============================================================================
# 数据加载（全部走 canon 的唯一读入口）
# =============================================================================
@st.cache_data(show_spinner="加载电影与用户信息…")
def load_catalog():
    movies = read_canon_table("movies").sort_values("iid").reset_index(drop=True)
    users = read_canon_table("users").sort_values("uid").reset_index(drop=True)
    return movies, users


@st.cache_data(show_spinner="加载评分历史…")
def load_ratings():
    return read_canon_table("ratings")


@st.cache_data(show_spinner="加载推荐结果…")
def load_top10(slug: str) -> pd.DataFrame | None:
    path = find_top10(slug)
    if path is None:
        return None
    df = pd.read_parquet(path)
    need = {"uid", "rank", "iid"}
    if not need.issubset(df.columns):
        return None
    if "score" not in df.columns:
        df = df.assign(score=float("nan"))
    return df[["uid", "rank", "iid", "score"]]


@st.cache_data(show_spinner=False)
def load_metrics(slug: str) -> dict | None:
    path = find_metrics(slug)
    if path is None:
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8")).get("reports", {})
    except Exception:
        return None


# =============================================================================
# 渲染辅助
# =============================================================================
def _fmt_genres(gs) -> str:
    return " / ".join(gs) if isinstance(gs, (list, tuple)) else str(gs)


def recommend_table(df_top10: pd.DataFrame, uid: int, movies: pd.DataFrame) -> pd.DataFrame:
    """把某个模型对 uid 的 top-10 拼上片名与类型。"""
    sub = df_top10[df_top10["uid"] == uid].sort_values("rank").head(K)
    if sub.empty:
        return pd.DataFrame()
    m = movies.set_index("iid")
    rows = []
    for r in sub.itertuples(index=False):
        iid = int(r.iid)
        if iid not in m.index:
            continue
        title = m.at[iid, "title"]
        year = m.at[iid, "year"]
        rows.append({
            "#": int(r.rank),
            "片名": f"{title}",
            "年份": int(year),
            "类型": _fmt_genres(m.at[iid, "genres"]),
            "分数": round(float(r.score), 4) if pd.notna(r.score) else None,
        })
    return pd.DataFrame(rows)


def metrics_table() -> pd.DataFrame:
    """汇总三个模型的 test 指标；缺的显示 —"""
    rows = []
    for name in MODELS:
        rep = load_metrics(MODEL_SLUG[name])
        if not rep:
            rows.append({"模型": name, "full R@10": None, "full NDCG@10": None,
                         "cand R@10": None, "cand NDCG@10": None})
            continue
        f = rep.get("full", {})
        c = rep.get("candidates", {})
        rows.append({
            "模型": name,
            "full R@10": round(f.get("recall", float("nan")), 4),
            "full NDCG@10": round(f.get("ndcg", float("nan")), 4),
            "cand R@10": round(c.get("recall", float("nan")), 4),
            "cand NDCG@10": round(c.get("ndcg", float("nan")), 4),
        })
    df = pd.DataFrame(rows).set_index("模型")
    # 转成 object 再替换，否则 float 列里的 None 仍会显示成 NaN
    return df.astype(object).where(df.notna(), "—")


def history_block(uid: int, ratings: pd.DataFrame, movies: pd.DataFrame) -> pd.DataFrame:
    m = movies.set_index("iid")
    hist = ratings[ratings["uid"] == uid].sort_values("ts").tail(10)
    rows = []
    for r in hist.itertuples(index=False):
        iid = int(r.iid)
        rows.append({
            "片名": m.at[iid, "title"] if iid in m.index else f"iid={iid}",
            "类型": _fmt_genres(m.at[iid, "genres"]) if iid in m.index else "",
            "星级": int(r.rating),
            "划分": str(r.split),
        })
    return pd.DataFrame(rows)


# =============================================================================
# 页面
# =============================================================================
def main() -> None:
    st.set_page_config(page_title="MovieLens 推荐系统演示", page_icon="🎬", layout="wide")

    st.title("🎬 MovieLens 电影推荐系统")
    st.caption(
        f"三个算法在同一套评估协议下对比 · "
        f"**{N_USERS:,} 用户 / {N_ITEMS:,} 部电影 / K={K}** · "
        "界面只读推荐结果文件，不加载模型"
    )

    movies, users = load_catalog()
    ratings = load_ratings()

    # ---- 顶部：三模型指标汇总 ----
    with st.expander("📊 三个算法的主结果（test，K=10）", expanded=False):
        st.dataframe(metrics_table(), use_container_width=True)
        st.caption(
            "**full** = 在全部 3,416 部电影里排序（主表）；**cand** = 1 正 + 100 负的 101 候选（副表）。"
            "两种模式的绝对值不可跨比。`Recall@10 ≡ HR@10` 是 Leave-One-Out 单正样本的必然结果。"
        )
        st.caption(
            "⚠️ 这三个数字来自不同成员的本地产物，`val` 只用于选超参，此处一律是 `test`。"
        )

    # ---- 顶部：产物状态 ----
    status = {n: find_top10(MODEL_SLUG[n]) is not None for n in MODELS}
    missing = [n for n, ok in status.items() if not ok]
    cols = st.columns(len(MODELS))
    for col, name in zip(cols, MODELS):
        ok = status[name]
        col.metric(
            label=f"{name} 推荐结果",
            value="✅ 就绪" if ok else "⬜ 缺失",
            help="读取 top10.parquet；缺失时该模型的对比列会显示提示",
        )
    if missing:
        st.warning(
            f"缺少 **{'、'.join(missing)}** 的 `top10.parquet`，对比区会显示为待生成。"
            " 补上后刷新页面即可，无需改代码。",
            icon="⚠️",
        )

    tab_user, tab_profile = st.tabs(["① 选一个用户（user）", "② 输入画像（sample profile）"])

    # =====================================================================
    # Tab 1：选用户 → 三算法并排对比
    # =====================================================================
    with tab_user:
        st.markdown("选择一位用户，查看**三个算法分别推荐了什么**。")

        c1, c2, c3 = st.columns([2, 1, 3])
        with c1:
            uid = st.number_input(
                "用户编号 uid（0 – %d，canon 编号，不是原始 UserID）" % (N_USERS - 1),
                min_value=0, max_value=N_USERS - 1, step=1, key="uid",
            )
        with c2:
            st.write("")
            st.write("")

            def _randomize() -> None:
                # on_click 回调在控件渲染之前执行，因此可以安全改写带 key 的控件值
                st.session_state["uid"] = int(random.randrange(N_USERS))

            st.button("🎲 随机换一个", use_container_width=True, on_click=_randomize)

        uid = int(uid)
        if uid in users["uid"].values:
            urow = users[users["uid"] == uid].iloc[0]
            st.markdown(
                f"**uid {uid}** · {urow['gender']} · {urow['age_group']} · "
                f"{urow['occupation']} · 共 {int((ratings['uid'] == uid).sum())} 条评分"
            )

        with st.expander("该用户最近 10 条评分（模型在训练时只能看到 train 部分）", expanded=False):
            st.dataframe(history_block(uid, ratings, movies), use_container_width=True, hide_index=True)

        st.divider()
        cols = st.columns(len(MODELS))
        for col, name in zip(cols, MODELS):
            slug = MODEL_SLUG[name]
            with col:
                st.subheader(name)
                df_top10 = load_top10(slug)
                if df_top10 is None:
                    st.info(
                        f"`{slug}` 的 top-10 尚未生成。\n\n"
                        f"需要 `results/{slug}/top10.parquet` "
                        f"或 `outputs/top10/{slug}.parquet`。",
                        icon="⬜",
                    )
                    continue
                tbl = recommend_table(df_top10, uid, movies)
                if tbl.empty:
                    st.warning("该模型没有这个用户的推荐记录。")
                else:
                    st.dataframe(tbl, use_container_width=True, hide_index=True)

        st.caption(
            "推荐已排除该用户**评过的全部影片**（train ∪ val ∪ test），"
            "符合任务书 “recommend movies that the user has not rated”。"
        )

    # =====================================================================
    # Tab 2：输入画像 → 冷启动近似
    # =====================================================================
    with tab_profile:
        st.markdown(
            "模拟一个**新用户**：给一个零交互的用户输入人口属性与偏好类型。\n\n"
            "> Item-CF 本身无法消费性别/年龄/类型（这正是冷启动问题），"
            "这里用「同群用户画像 → 伪历史 → 邻域扩散」的近似方案。"
        )

        p1, p2, p3 = st.columns([1, 1, 3])
        with p1:
            gender_label = st.radio("性别", ["不限", "男", "女"], horizontal=True)
        with p2:
            age_options = ["不限"] + list(dict.fromkeys(users["age_group"].astype(str)))
            age_label = st.selectbox("年龄段", age_options)
        with p3:
            genre_options = sorted({g for gs in movies["genres"] for g in gs})
            genres = st.multiselect("喜欢的类型（可多选）", genre_options, default=["Comedy", "Romance"])

        top_n = st.slider("推荐数量", 5, 20, K)

        if st.button("🎯 生成推荐", type="primary"):
            gender = {"不限": None, "男": "M", "女": "F"}[gender_label]
            age = None if age_label == "不限" else age_label
            with st.spinner("正在按人群画像计算…"):
                try:
                    from src.demo_profile import Profile, recommend_for_profile

                    prof = Profile(gender, age, tuple(genres))
                    res = recommend_for_profile(prof, top_n=top_n)
                except Exception as exc:  # noqa: BLE001
                    st.error(f"生成失败：{exc}")
                    st.stop()

            st.success(
                f"匹配人群 **{res['cohort_size']:,}** 人（{' / '.join(res['notes'])}）"
            )
            m = movies.set_index("iid")
            rows = []
            for i, iid in enumerate(res["top"], 1):
                iid = int(iid)
                rows.append({
                    "#": i,
                    "片名": m.at[iid, "title"],
                    "年份": int(m.at[iid, "year"]),
                    "类型": _fmt_genres(m.at[iid, "genres"]),
                    "分数": round(float(res["scores"][iid]), 4),
                })
            st.dataframe(pd.DataFrame(rows), use_container_width=True, hide_index=True)

            with st.expander("这一步是怎么算的（伪历史）", expanded=False):
                st.markdown(
                    "系统从同群用户里挑出偏好最高的 30 部电影，当作这个「新用户」看过的片，"
                    "再用 Item-CF 的相似度矩阵向外扩散。下面是借来的「历史」："
                )
                prow = []
                for i, iid in enumerate(res["pseudo"][:15], 1):
                    iid = int(iid)
                    prow.append({
                        "#": i,
                        "片名": m.at[iid, "title"],
                        "类型": _fmt_genres(m.at[iid, "genres"]),
                        "人群偏好": round(float(res["affinity"][iid]), 3),
                        "评过人数": int(res["n_raters"][iid]),
                    })
                st.dataframe(pd.DataFrame(prow), use_container_width=True, hide_index=True)

            st.caption(
                "这是冷启动的**近似**方案，同时作为对照基线。"
                "原生支持用户特征的是 LightFM —— 它把用户表示写成属性 embedding 之和。"
            )

    st.divider()
    st.caption(
        "数据：MovieLens-1M (GroupLens) · 引用 Harper & Konstan, TiiS 2019, DOI 10.1145/2827872 · "
        "原始数据不得再分发"
    )


if __name__ == "__main__":
    main()
